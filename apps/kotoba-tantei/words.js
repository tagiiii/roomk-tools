/**
 * ランダムな単語セットを取得
 * @returns {WordSet}
 */
export function getRandomWordSet() {
  const randomIndex = Math.floor(Math.random() * wordSets.length);
  return wordSets[randomIndex];
}

/**
 * IDで単語セットを取得
 * @param {string} id
 * @returns {WordSet | undefined}
 */
export function getWordSetById(id) {
  return wordSets.find((set) => set.id === id);
}
