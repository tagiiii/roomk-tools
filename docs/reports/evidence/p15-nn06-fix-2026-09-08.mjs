import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const baseline = 'dfd65d07082a337e4d4cfa14d4ac1ca54176570e';
const before = execFileSync('git', ['show', baseline + ':apps/quiz/questions.js'], { cwd: root, encoding: 'utf8' });
const after = readFileSync(new URL('../../../apps/quiz/questions.js', import.meta.url), 'utf8');
const original = '青森県の町名・JR駅名「大鰐」は、何と読む？';
const replacement = '青森県の町名「大鰐」は、何と読む？';
assert.equal(before.split(original).length - 1, 1);
assert.equal(after, before.replace(original, replacement), 'Unapproved source changes');
const parse = async text => (await import('data:text/javascript;base64,' + Buffer.from(text).toString('base64'))).QUIZ_PACKS;
const oldPacks = await parse(before), packs = await parse(after);
assert.equal(packs.length, 24);
const expected = structuredClone(oldPacks);
const questions = expected.flatMap(p => p.questions);
assert.equal(questions.length, 480);
assert.equal(new Set(questions.map(q => q.id)).size, 480);
const target = questions.find(q => q.id === 'nn06');
assert.equal(target.question, original);
target.question = replacement;
assert.deepEqual(packs, expected, 'Question fields or pack metadata changed');
assert.deepEqual(target.choices, ['たいがく', 'おおわに', 'おおがく']);
assert.equal(target.answerIndex, 1);
assert.equal(target.difficulty, 2);
